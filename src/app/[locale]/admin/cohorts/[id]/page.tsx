import { notFound } from "next/navigation";

import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow
} from "@/components/ui/table";
import { Textarea } from "@/components/ui/textarea";
import type { Locale } from "@/i18n/routing";
import { createServerClient } from "@/lib/supabase/server";
import { updateCohortAction } from "@/server/actions/admin";
import { requireAdmin } from "@/server/queries/auth";
import { getSeasons } from "@/server/queries/data";

async function getCohort(id: string) {
  const supabase = createServerClient();
  const { data } = await supabase
    .from("cohorts")
    .select("*, cohort_sessions(*)")
    .eq("id", id)
    .maybeSingle();

  return data;
}

export default async function AdminCohortDetailPage({
  params
}: {
  params: { locale: Locale; id: string };
}) {
  await requireAdmin(params.locale);
  const [cohort, seasons] = await Promise.all([getCohort(params.id), getSeasons()]);

  if (!cohort) notFound();

  const sessions = [...(cohort.cohort_sessions ?? [])].sort(
    (a, b) => a.session_number - b.session_number
  );

  return (
    <section className="space-y-8">
      <div>
        <p className="text-sm font-semibold uppercase tracking-[0.18em] text-primary">Phase 3</p>
        <h1 className="mt-2 font-display text-4xl font-bold">{cohort.name}</h1>
        <p className="mt-3 text-sm text-muted-foreground">
          Edit the cohort record. The four sessions are generated by the database when the cohort is
          created.
        </p>
      </div>

      <Card>
        <CardHeader>
          <CardTitle>Edit cohort</CardTitle>
        </CardHeader>
        <CardContent>
          <form action={updateCohortAction} className="grid gap-4 md:grid-cols-4">
            <input type="hidden" name="locale" value={params.locale} />
            <input type="hidden" name="cohort_id" value={cohort.id} />
            <div className="space-y-2 md:col-span-2">
              <Label htmlFor="season_id">Season</Label>
              <select
                id="season_id"
                name="season_id"
                defaultValue={cohort.season_id}
                className="h-11 w-full rounded-md border border-input bg-secondary px-3 text-sm"
              >
                {seasons.map((season) => (
                  <option key={season.id} value={season.id}>
                    {season.name}
                  </option>
                ))}
              </select>
            </div>
            <div className="space-y-2 md:col-span-2">
              <Label htmlFor="name">Name</Label>
              <Input id="name" name="name" defaultValue={cohort.name} required />
            </div>
            <div className="space-y-2">
              <Label htmlFor="cohort_number">Number</Label>
              <Input
                id="cohort_number"
                name="cohort_number"
                type="number"
                defaultValue={cohort.cohort_number}
                required
              />
            </div>
            <div className="space-y-2">
              <Label htmlFor="start_date">Start</Label>
              <Input
                id="start_date"
                name="start_date"
                type="date"
                defaultValue={cohort.start_date}
                required
              />
            </div>
            <div className="space-y-2">
              <Label htmlFor="end_date">End</Label>
              <Input
                id="end_date"
                name="end_date"
                type="date"
                defaultValue={cohort.end_date}
                required
              />
            </div>
            <div className="space-y-2">
              <Label htmlFor="day_of_week">Day</Label>
              <Input
                id="day_of_week"
                name="day_of_week"
                type="number"
                min="0"
                max="6"
                defaultValue={cohort.day_of_week ?? ""}
                placeholder="0-6"
              />
            </div>
            <div className="space-y-2">
              <Label htmlFor="start_time">Start time</Label>
              <Input
                id="start_time"
                name="start_time"
                type="time"
                defaultValue={cohort.start_time}
                required
              />
            </div>
            <div className="space-y-2">
              <Label htmlFor="end_time">End time</Label>
              <Input
                id="end_time"
                name="end_time"
                type="time"
                defaultValue={cohort.end_time}
                required
              />
            </div>
            <div className="space-y-2">
              <Label htmlFor="capacity">Capacity</Label>
              <Input
                id="capacity"
                name="capacity"
                type="number"
                defaultValue={cohort.capacity}
                required
              />
            </div>
            <div className="space-y-2">
              <Label htmlFor="status">Status</Label>
              <select
                id="status"
                name="status"
                defaultValue={cohort.status}
                className="h-11 w-full rounded-md border border-input bg-secondary px-3 text-sm"
              >
                {["draft", "open", "active", "completed", "cancelled"].map((status) => (
                  <option key={status} value={status}>
                    {status}
                  </option>
                ))}
              </select>
            </div>
            <div className="space-y-2 md:col-span-2">
              <Label htmlFor="location_name">Location</Label>
              <Input
                id="location_name"
                name="location_name"
                defaultValue={cohort.location_name}
                required
              />
            </div>
            <div className="space-y-2 md:col-span-2">
              <Label htmlFor="location_address">Address</Label>
              <Input
                id="location_address"
                name="location_address"
                defaultValue={cohort.location_address}
                required
              />
            </div>
            <div className="space-y-2">
              <Label htmlFor="regular_price_cad">Regular</Label>
              <Input
                id="regular_price_cad"
                name="regular_price_cad"
                type="number"
                defaultValue={cohort.regular_price_cad}
              />
            </div>
            <div className="space-y-2">
              <Label htmlFor="returning_price_cad">Returning</Label>
              <Input
                id="returning_price_cad"
                name="returning_price_cad"
                type="number"
                defaultValue={cohort.returning_price_cad}
              />
            </div>
            <div className="space-y-2">
              <Label htmlFor="registration_status">Registration</Label>
              <select
                id="registration_status"
                name="registration_status"
                defaultValue={cohort.registration_status}
                className="h-11 w-full rounded-md border border-input bg-secondary px-3 text-sm"
              >
                {["closed", "open", "full"].map((status) => (
                  <option key={status} value={status}>
                    {status}
                  </option>
                ))}
              </select>
            </div>
            <div className="space-y-2 md:col-span-2">
              <Label htmlFor="description_en">Description EN</Label>
              <Textarea
                id="description_en"
                name="description_en"
                defaultValue={cohort.description_en ?? ""}
              />
            </div>
            <div className="space-y-2 md:col-span-2">
              <Label htmlFor="description_fr">Description FR</Label>
              <Textarea
                id="description_fr"
                name="description_fr"
                defaultValue={cohort.description_fr ?? ""}
              />
            </div>
            <div className="md:col-span-4">
              <Button>Save cohort</Button>
            </div>
          </form>
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle>Generated sessions</CardTitle>
        </CardHeader>
        <CardContent className="overflow-x-auto">
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Session</TableHead>
                <TableHead>Date</TableHead>
                <TableHead>Time</TableHead>
                <TableHead>Theme EN</TableHead>
                <TableHead>Theme FR</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {sessions.map((session) => (
                <TableRow key={session.id}>
                  <TableCell>{session.session_number}</TableCell>
                  <TableCell>{session.session_date}</TableCell>
                  <TableCell>
                    {session.start_time} - {session.end_time}
                  </TableCell>
                  <TableCell>{session.theme_en ?? "Not set"}</TableCell>
                  <TableCell>{session.theme_fr ?? "Not set"}</TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </CardContent>
      </Card>
    </section>
  );
}
